#!/usr/bin/env python3
"""Embed the Wi-Fi transfer web page into the firmware.

    python tools/embed_web_page.py

Reads  lib/microreader/net/web/index.html
Writes lib/microreader/net/WebPage.h  (a byte array plus the source's CRC-32)

Run it after editing index.html. A unit test (WebPageEmbedded) fails when the
header is out of date.
"""

import os
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "lib", "microreader", "net", "web", "index.html")
DST = os.path.join(ROOT, "lib", "microreader", "net", "WebPage.h")


def main():
    data = open(SRC, "rb").read()
    crc = zlib.crc32(data) & 0xFFFFFFFF
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    out = f"""// Generated by tools/embed_web_page.py from net/web/index.html. Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>

namespace microreader {{
namespace net {{

// CRC-32 (zlib) of index.html when this header was generated.
static constexpr uint32_t kWebPageSourceCrc32 = 0x{crc:08x};

alignas(4) static constexpr uint8_t kWebPage[] = {{
{chr(10).join(lines)}
}};
static constexpr size_t kWebPageSize = sizeof(kWebPage);

}}  // namespace net
}}  // namespace microreader
"""
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"[embed_web_page] {len(data):,} bytes, crc32=0x{crc:08x} -> {os.path.relpath(DST, ROOT)}")


if __name__ == "__main__":
    main()
